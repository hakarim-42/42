#include "libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*ptr;

	if (!lst || !new)
		return ;
	if (!*lst)
	{
		*lst = new;
		return ;
	}
	ptr = lst[0];
	while (ptr->next != NULL)
		ptr = ptr->next;
	ptr->next = new;
}
